"""Vrai PostgreSQL 15 local ; signaux réseau/AWS simulés, aucune ressource cloud.

Lancer via run_docker_postgres.py --scenario total-outage uniquement.
"""
from contextlib import contextmanager
import os
from pathlib import Path
import sys
import time
import unittest
from unittest.mock import Mock
from uuid import uuid4

import psycopg
from psycopg.conninfo import conninfo_to_dict, make_conninfo

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import automation
import database
import postgres_contract
from test_automation import MemoryStore, profile

# Profil de la plateforme : le schéma est celui de l'application, lu dans la base (ici créé à l'identique des deux côtés,
# comme le fait la restauration du schéma avant l'abonnement).
PROFILE = postgres_contract.encode({'database': 'cnp_local_admin'})
APP_SCHEMA = ("CREATE TABLE public.pensees (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
              "texte text NOT NULL, saved_at timestamp NOT NULL DEFAULT timezone('UTC', now()))")


@unittest.skipUnless(os.getenv('CNP_LOCAL_OUTAGE_TEST') == '1', 'Utiliser le scénario Docker total-outage explicite')
class OutagePostgresTests(unittest.TestCase):
    def test_worker_pause_resume_promotion_new_write_and_source_return(self):
        dsns=[os.environ['CNP_LOCAL_SOURCE_DSN'],os.environ['CNP_LOCAL_TARGET_DSN']]
        infos=[conninfo_to_dict(dsn) for dsn in dsns]
        self.assertNotEqual(infos[0]['port'],infos[1]['port'])
        for info in infos:
            self.assertEqual(info['host'],'127.0.0.1')
            self.assertEqual(info['user'],'cnp_local_admin')
            self.assertEqual(info['dbname'],'cnp_local_admin')
        with psycopg.connect(dsns[0],autocommit=True) as source, psycopg.connect(dsns[1],autocommit=True) as target:
            for conn in (source,target):
                self.assertEqual(conn.info.server_version//10000,15)
                conn.execute('CREATE ROLE cnp_runtime LOGIN')
                conn.execute('CREATE ROLE cnp_replication LOGIN REPLICATION')
                conn.execute(APP_SCHEMA)
                database.install_schema(conn,PROFILE)
            database.configure_runtime(source,False,PROFILE)
            database.configure_runtime(target,True,PROFILE)
            database.publisher(source,PROFILE)
            # Le transport sans TLS est réservé au réseau Docker jetable ; il
            # ne passe jamais par les outils de configuration cloud.
            database.subscribe(target,os.environ['CNP_LOCAL_REPLICATION_DSN'],PROFILE)
            source.execute("INSERT INTO public.pensees(texte) VALUES('avant panne')")
            barrier=uuid4();source.execute('INSERT INTO public.replication_barrier(id) VALUES(%s)',(barrier,))
            database.wait_replay(target,barrier,timeout=30,profile=PROFILE)
            known=database.subscriber_observation(target,PROFILE)
            self.assertTrue(known['tables_ready'])
            self.assertTrue(known['replayed_lsn'])
            # Arrêt du sender : le worker doit promouvoir uniquement avec sa
            # cible locale et la connaissance préalable de la réplication.
            source.execute('ALTER ROLE cnp_replication NOLOGIN')
            source.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE usename='cnp_replication'")
            store=MemoryStore()
            store.evidence={'observed_at':int(time.time()),'last_message_at':known['last_message_at'],
                'replayed_lsn':known['replayed_lsn']}
            signals=Mock();signals.outage_confirmed.return_value=True;signals.source_available.return_value=False
            routing=Mock()
            class LocalSQL(automation.SQL):
                def __init__(self):
                    self.pause_once=True
                    self.source_connections=0
                @contextmanager
                def connection(self, app, side):
                    if side == 'source':
                        self.source_connections+=1
                        if not signals.source_available(app):raise OSError('source indisponible simulée')
                    yield source if side == 'source' else target
                def standby_ready(self, target, app):
                    # Seuls endpoint, nom de base et TLS diffèrent dans Docker.
                    self_state=database.progress(target,app['profile'])
                    automation.require(self_state['enabled'] and self_state['tables_ready'],'BLOCKED_REPLICATION')
                    automation.require(target.execute("SELECT rolcanlogin FROM pg_roles WHERE rolname='cnp_runtime'").fetchone()==(False,),
                        'BLOCKED_TARGET_OPEN')
                def promote_outage(self, target, app, evidence, checkpoint, on_stage):
                    def check():
                        if self.pause_once and self.saved_state(target,app['profile']) == 'AWS_ACTIVE':
                            self.pause_once=False;store.paused=True
                        checkpoint()
                    return database.promote_unreachable(target,evidence,profile=app['profile'],checkpoint=check,on_stage=on_stage)
            sql=LocalSQL();worker=automation.Worker(store,signals,sql,routing);app={**profile(),'profile':PROFILE}
            self.assertEqual(worker.run(app),'PAUSED_OR_LEASE_LOST')
            self.assertEqual(sql.saved_state(target,PROFILE),'PROMOTING')
            self.assertEqual(target.execute("SELECT rolcanlogin FROM pg_roles WHERE rolname='cnp_runtime'").fetchone(),(False,))
            self.assertEqual(sql.source_connections,0)
            store.paused=False
            self.assertEqual(worker.run(app),'AWS_ACTIVE')
            self.assertEqual(sql.source_connections,0)
            runtime=make_conninfo(**{**infos[1],'user':'cnp_runtime'})
            with psycopg.connect(runtime,autocommit=True) as app_conn:
                identifier=app_conn.execute("INSERT INTO public.pensees(texte) VALUES('après panne AWS') RETURNING id").fetchone()[0]
                self.assertGreater(identifier,1)
            signals.source_available.return_value=True
            signals.outage_confirmed.return_value=False
            self.assertEqual(worker.run(app),'AWS_ACTIVE')
            self.assertEqual(store.fence,'GCP_FENCED')
            self.assertEqual(source.execute("SELECT rolcanlogin FROM pg_roles WHERE rolname='cnp_runtime'").fetchone(),(False,))
            self.assertTrue(all(call.args[1] is True for call in routing.set_closed.call_args_list))
            self.assertEqual(target.execute('SELECT count(*) FROM public.pensees').fetchone()[0],2)


if __name__ == '__main__':
    unittest.main()
