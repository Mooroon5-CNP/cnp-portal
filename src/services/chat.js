'use strict';

// Portal side of the CNP assistant chat (CNP-046), following the CNP-040
// contract: the portal validates the ChatTurnRequest, builds the KnownContext
// deterministically, issues a short-lived internal token for the AI client
// and only forwards an allowlisted, sanitized subset of ChatEvents to the
// browser. Portal cookies, GitHub tokens and provider errors never leave
// the backend.

const crypto = require('crypto');
const { v4: uuidv4 } = require('uuid');

const READ_ONLY_TOOLS = [
  'list_applications',
  'get_deployment_status',
  'get_application_logs',
  'get_finops_recommendation',
];
const ENVIRONMENTS = ['dev', 'prod'];
const MAX_MESSAGE_LENGTH = 2000;
const TOKEN_TTL_SECONDS = 5 * 60;

// User-facing messages are owned by the portal: codes coming from the AI
// client are mapped here, their original message is never displayed.
const ERRORS = {
  UNAUTHENTICATED:              { category: 'forbidden',   message: 'Votre session a expiré. Reconnectez-vous pour continuer.' },
  FORBIDDEN:                    { category: 'forbidden',   message: 'Vous n\'avez pas accès à cette information.' },
  APPLICATION_NOT_FOUND:        { category: 'not_found',   message: 'Cette application n\'est pas enregistrée sur la plateforme CNP.' },
  ENVIRONMENT_NOT_FOUND:        { category: 'not_found',   message: 'Cet environnement n\'existe pas pour cette application.' },
  INVALID_INPUT:                { category: 'invalid',     message: 'La demande n\'est pas valide.' },
  OBSERVABILITY_NOT_CONFIGURED: { category: 'unavailable', message: 'Cette application n\'est pas encore reliée à Datadog.' },
  SOURCE_UNAVAILABLE:           { category: 'unavailable', message: 'Une source de données est momentanément indisponible.' },
  RATE_LIMITED:                 { category: 'unavailable', message: 'Trop de demandes en peu de temps. Réessayez dans quelques secondes.' },
  AI_CLIENT_UNAVAILABLE:        { category: 'unavailable', message: 'L\'assistant est momentanément indisponible. Votre conversation est conservée, vous pouvez réessayer.' },
  INTERNAL_ERROR:               { category: 'unavailable', message: 'Une erreur inattendue est survenue. Votre conversation est conservée, vous pouvez réessayer.' },
  SOURCE_TIMEOUT:               { category: 'timeout',     message: 'Une source de données a mis trop de temps à répondre.' },
  TIMEOUT:                      { category: 'timeout',     message: 'L\'assistant a mis trop de temps à répondre. Réessayez dans un instant.' },
};

const WARNINGS = {
  FINOPS_COST_DATA_UNAVAILABLE: 'Aucune source de coûts n\'est configurée : la recommandation repose uniquement sur l\'utilisation des ressources, sans montant.',
  INSUFFICIENT_METRICS:         'Les métriques disponibles sont insuffisantes : la recommandation est peu fiable.',
  SOURCE_UNAVAILABLE:           'Une source était indisponible : la réponse est partielle.',
  SOURCE_TIMEOUT:               'Une source n\'a pas répondu à temps : la réponse est partielle.',
  OBSERVABILITY_NOT_CONFIGURED: 'Cette application n\'est pas encore reliée à Datadog.',
  RATE_LIMITED:                 'Une source a limité le nombre de requêtes : la réponse est partielle.',
};
const DEFAULT_WARNING = 'Certaines données sont manquantes : la réponse est partielle.';

const OUT_OF_SCOPE_MESSAGE =
  'Cette demande implique une modification (déploiement, redimensionnement, migration, synchronisation, suppression…). ' +
  'L\'assistant CNP est en lecture seule : aucune action n\'a été exécutée. Utilisez les écrans dédiés du portail pour ce type d\'opération.';

const STRUCTURED_KINDS = ['application_list', 'deployment_status', 'application_logs', 'finops_recommendation'];

// ---------------------------------------------------------------------------
// Request validation and KnownContext
// ---------------------------------------------------------------------------

function validateTurnRequest(body) {
  if (!body || typeof body !== 'object') return { ok: false };
  const message = typeof body.message === 'string' ? body.message.trim() : '';
  if (!message || message.length > MAX_MESSAGE_LENGTH) return { ok: false };
  const conversationId = typeof body.conversationId === 'string' && /^[\w-]{8,64}$/.test(body.conversationId)
    ? body.conversationId
    : uuidv4();
  const context = body.context && typeof body.context === 'object' ? body.context : {};
  return { ok: true, value: { message, conversationId, context } };
}

/**
 * Deterministic KnownContext (never generated by an AI): only a registered
 * application and a known environment, taken from the UI selection or named
 * verbatim in the message. Anything else is dropped.
 */
function buildKnownContext({ context, message }, registeredApps) {
  const apps = new Set(registeredApps);
  const known = {};

  if (typeof context.applicationId === 'string' && apps.has(context.applicationId)) {
    known.applicationId = context.applicationId;
  } else {
    const words = new Set(message.toLowerCase().split(/[^a-z0-9-]+/));
    const mentioned = registeredApps.filter(a => words.has(a.toLowerCase()));
    if (mentioned.length === 1) known.applicationId = mentioned[0];
  }

  if (ENVIRONMENTS.includes(context.environment)) {
    known.environment = context.environment;
  } else {
    const env = ENVIRONMENTS.filter(e => new RegExp(`\\b${e}\\b`, 'i').test(message));
    if (env.length === 1) known.environment = env[0];
  }
  return known;
}

// ---------------------------------------------------------------------------
// Internal token (portal → AI client → MCP), HS256, 5 minutes
// ---------------------------------------------------------------------------

function base64url(input) {
  return Buffer.from(input).toString('base64url');
}

function issueInternalToken(user, secret, now = Math.floor(Date.now() / 1000)) {
  if (!secret) throw new Error('CHAT_INTERNAL_TOKEN_SECRET is not configured');
  const header = { alg: 'HS256', typ: 'JWT' };
  const payload = {
    iss: 'cnp-portal',
    aud: 'cnp-mcp',
    sub: String(user.githubId || user.id),
    login: user.username,
    role: 'cnp_reader',
    scopes: ['cnp:read'],
    iat: now,
    exp: now + TOKEN_TTL_SECONDS,
    jti: uuidv4(),
  };
  const unsigned = `${base64url(JSON.stringify(header))}.${base64url(JSON.stringify(payload))}`;
  const signature = crypto.createHmac('sha256', secret).update(unsigned).digest('base64url');
  return `${unsigned}.${signature}`;
}

// ---------------------------------------------------------------------------
// ChatEvent sanitization (AI client → browser)
// ---------------------------------------------------------------------------

function errorEvent(code, correlationId) {
  const known = ERRORS[code] || ERRORS.INTERNAL_ERROR;
  return {
    type: 'error',
    data: {
      code: ERRORS[code] ? code : 'INTERNAL_ERROR',
      category: known.category,
      message: known.message,
      retryable: known.category !== 'forbidden' && known.category !== 'invalid',
      correlationId,
    },
  };
}

function shortString(v, max = 120) {
  return typeof v === 'string' && v.length > 0 ? v.slice(0, max) : null;
}

function safeCorrelationId(v, fallback) {
  return typeof v === 'string' && /^[\w-]{1,64}$/.test(v) ? v : fallback;
}

/** Returns the event to forward to the browser, or null to drop it. */
function sanitizeEvent(event, correlationId) {
  if (!event || typeof event !== 'object') return null;
  const d = event.data && typeof event.data === 'object' ? event.data : {};

  switch (event.type) {
    case 'tool_status':
      if (!READ_ONLY_TOOLS.includes(d.tool) || !['running', 'completed', 'failed'].includes(d.state)) return null;
      return { type: 'tool_status', data: { tool: d.tool, state: d.state } };

    case 'answer_delta':
      if (typeof d.text !== 'string') return null;
      return { type: 'answer_delta', data: { text: d.text.slice(0, 8000) } };

    case 'source': {
      const source = shortString(d.source, 64);
      if (!source || !['available', 'unavailable', 'not_configured'].includes(d.status)) return null;
      return { type: 'source', data: { source, status: d.status, retrievedAt: shortString(d.retrievedAt, 40) } };
    }

    case 'warning': {
      const code = typeof d.code === 'string' && /^[A-Z_]{2,64}$/.test(d.code) ? d.code : 'PARTIAL_DATA';
      return { type: 'warning', data: { code, message: WARNINGS[code] || DEFAULT_WARNING, source: shortString(d.source, 64) } };
    }

    case 'clarification_required': {
      const question = shortString(d.question, 500);
      if (!question) return null;
      const options = Array.isArray(d.options) ? d.options.map(o => shortString(o, 120)).filter(Boolean).slice(0, 5) : [];
      return { type: 'clarification_required', data: { question, options } };
    }

    case 'rejected':
      return { type: 'rejected', data: { reason: 'out_of_scope', message: OUT_OF_SCOPE_MESSAGE } };

    case 'structured':
      if (!STRUCTURED_KINDS.includes(d.kind) || !d.data || typeof d.data !== 'object') return null;
      return { type: 'structured', data: { kind: d.kind, data: d.data } };

    case 'completed':
      return {
        type: 'completed',
        data: {
          status: ['success', 'partial', 'error'].includes(d.status) ? d.status : 'success',
          correlationId: safeCorrelationId(d.correlationId, correlationId),
        },
      };

    case 'error':
      return errorEvent(d.code, safeCorrelationId(d.correlationId, correlationId));

    default:
      return null;
  }
}

module.exports = {
  READ_ONLY_TOOLS,
  ENVIRONMENTS,
  OUT_OF_SCOPE_MESSAGE,
  validateTurnRequest,
  buildKnownContext,
  issueInternalToken,
  sanitizeEvent,
  errorEvent,
};
